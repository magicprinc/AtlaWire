"""Contracts for the frozen release inventory and its two-way check.

The artifact is only trustworthy if a change in either direction fails, so these
tests rebuild it from the live mappings and assert the exact totals, the exact
per-row linkage, and that the committed bytes are the regenerated bytes.
"""

import importlib.util
import json
import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
INVENTORY = ROOT / ".development" / "rest-inventory.json"
PLACEHOLDER = re.compile(r"\{[^{}]+\}")


def _load_generator():
    spec = importlib.util.spec_from_file_location(
        "build_rest_inventory", ROOT / "tools" / "build_rest_inventory.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _normalize(path: str) -> str:
    return PLACEHOLDER.sub("{}", path.rstrip("/"))


@pytest.fixture(scope="module")
def built():
    return _load_generator().build_document()


def test_committed_inventory_is_the_regenerated_document():
    """A hand-edited or stale artifact must not survive the check."""
    generator = _load_generator()
    document = generator.build_document()

    assert generator.render(document) == INVENTORY.read_text(encoding="utf-8")


def test_frozen_totals_are_exact(built):
    """251 would mean a lost row; 202 a silently added one."""
    assert built["totals"] == {
        "documented_rows": 252,
        "rows_with_disposition": 248,
        "required": 201,
        "excluded": 51,
        "unresolved": 0,
        "runtime_operations": 202,
    }


def test_every_required_row_is_a_registered_operation(built):
    """`required` is a promise, so each row must resolve to one runtime id."""
    missing = [
        (product, row["method"], row["path"])
        for product, block in built["products"].items()
        for row in block["rows"]
        if row["disposition"] == "required" and row["runtime_operation_id"] is None
    ]

    assert missing == []


def test_every_excluded_row_is_absent_from_the_registry(built):
    """An excluded route that is registered contradicts its own reason."""
    registered = [
        (product, row["method"], row["path"])
        for product, block in built["products"].items()
        for row in block["rows"]
        if row["disposition"] == "excluded" and row["registered"]
    ]

    assert registered == []


def test_every_excluded_row_states_a_known_reason(built):
    """A reason code without text is not an audit trail."""
    reasons = {
        row["reason"]
        for block in built["products"].values()
        for row in block["rows"]
        if row["disposition"] == "excluded"
    } | {
        row["reason"]
        for block in built["products"].values()
        for row in block["excluded_by_rule"]
    }

    assert reasons == {
        "administrative",
        "authorization-uncertain",
        "documented-inconsistently",
        "system-route",
    }


def test_verify_reports_no_problem_for_the_built_document(built):
    assert _load_generator().verify(built) == []


def test_verify_catches_a_required_row_that_disappears(built):
    """The check must fail when the registry drops a required operation."""
    generator = _load_generator()
    broken = json.loads(json.dumps(built))
    row = next(
        row
        for block in broken["products"].values()
        for row in block["rows"]
        if row["disposition"] == "required"
    )
    row["path"] = "/rest/api/2/does-not-exist"

    problems = generator.verify(broken)

    assert any("required but unregistered" in problem for problem in problems)


def test_verify_catches_an_unaccounted_runtime_operation(built):
    """A new registered read must be dispositioned, not absorbed silently."""
    generator = _load_generator()
    broken = json.loads(json.dumps(built))
    broken["registered_additions"] = []

    problems = generator.verify(broken)

    assert any("unaccounted for" in problem for problem in problems)


def test_verify_catches_a_drifted_total(built):
    generator = _load_generator()
    broken = json.loads(json.dumps(built))
    broken["totals"]["required"] = 200

    assert any(
        "required: expected 201" in problem for problem in generator.verify(broken)
    )


def test_verify_catches_a_compensating_per_product_shift(built):
    """201 must not be reachable by one product short and another long."""
    generator = _load_generator()
    broken = json.loads(json.dumps(built))
    broken["products"]["jira"]["counts"]["required"] = 107
    broken["products"]["confluence"]["counts"]["required"] = 37

    problems = generator.verify(broken)

    assert any("jira counts.required disagrees" in problem for problem in problems)
    assert any(
        "confluence counts.required disagrees" in problem for problem in problems
    )


def test_verify_catches_an_addition_that_masks_a_required_row(built):
    """A named addition must never stand in for a required row."""
    generator = _load_generator()
    broken = json.loads(json.dumps(built))
    masked = next(
        row
        for block in broken["products"].values()
        for row in block["rows"]
        if row["disposition"] == "required"
    )
    broken["registered_additions"].append(
        {
            "runtime_operation_id": masked["runtime_operation_id"],
            "product": next(
                product
                for product, block in broken["products"].items()
                if masked in block["rows"]
            ),
            "method": masked["method"],
            "path": masked["path"],
            "reason": "duplicate of a required row",
        }
    )

    assert any(
        "masks a required row" in problem for problem in generator.verify(broken)
    )


def test_verify_catches_a_duplicate_registry_key(monkeypatch, built):
    """Two operations on one route would hide a lost row behind a stable total."""
    generator = _load_generator()
    census = generator.operations_census()
    monkeypatch.setattr(
        generator, "operations_census", lambda: [*census, dict(census[0])]
    )

    problems = generator.verify(built)

    assert any("duplicate registry keys" in problem for problem in problems)


def test_per_product_required_counts_are_pinned(built):
    """The split is part of the freeze, not just the global total."""
    assert {
        product: block["counts"]["required"]
        for product, block in built["products"].items()
    } == {"jira": 108, "confluence": 36, "bitbucket": 57}


def test_verify_checks_the_confluence_rule_against_the_mapping_prose(built):
    """The hard-coded audit paths must still be named in the mapping itself."""
    generator = _load_generator()

    assert generator._rule_text_names_every_audit_path() == []


def test_normalize_path_collapses_placeholder_names():
    """Two spellings of one route must compare equal, or the linkage breaks."""
    generator = _load_generator()

    assert generator.normalize_path("/a/{id}/b/") == generator.normalize_path(
        "/a/{issueIdOrKey}/b"
    )
    assert generator.normalize_path("/a/b") == "/a/b"
